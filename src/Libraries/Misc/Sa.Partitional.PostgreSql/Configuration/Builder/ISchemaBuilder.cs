namespace Sa.Partitional.PostgreSql;

/// <summary>
/// Builder for declaring one or more database schemas and the tables they contain.
/// </summary>
public interface ISchemaBuilder
{
    /// <summary>
    /// Creates an empty table definition builder. At least one column has to be added afterwards
    /// (<see cref="AddTable"/> or <see cref="ITableBuilder.AddFields"/>) - the first declared column
    /// becomes the primary key id column, and <see cref="Build"/> fails without it.
    /// </summary>
    /// <param name="tableName">The logical table name (without schema prefix).</param>
    /// <returns>A fluent <see cref="ITableBuilder"/> for further configuration.</returns>
    ITableBuilder CreateTable(string tableName);

    /// <summary>
    /// Creates a new table definition builder with explicitly provided SQL field definitions.
    /// </summary>
    /// <param name="tableName">The logical table name (without schema prefix).</param>
    /// <param name="sqlFields">Raw SQL column definitions, e.g. <c>"created_at bigint NOT NULL"</c>.</param>
    /// <returns>A fluent <see cref="ITableBuilder"/> for further configuration.</returns>
    ITableBuilder AddTable(string tableName, params string[] sqlFields);

    /// <summary>
    /// Registers an <b>existing plain table</b> to be converted into a partitioned one on the first
    /// migration and then managed by the library.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The table must already exist and must not be partitioned: only tables without partitions are
    /// adopted. A root that is already partitioned, or a missing table, is rejected on the first
    /// migration with an actionable error instead of being modified.
    /// </para>
    /// <para>
    /// The declared fields describe the target partitioned root and are verified against the live
    /// table — the column set has to match exactly. The conversion happens once, inside a single
    /// transaction, and keeps the original table as a backup; repeated runs are no-ops.
    /// </para>
    /// <para>
    /// Do not carry a <c>PRIMARY KEY</c> clause over from the existing table: the library emits its
    /// own primary-key constraint (which has to include the partition key), so declaring one inline
    /// would create a second constraint.
    /// </para>
    /// </remarks>
    /// <param name="tableName">The existing table name (without schema prefix).</param>
    /// <param name="sqlFields">
    /// Raw SQL column definitions, e.g. <c>"id bigint GENERATED BY DEFAULT AS IDENTITY"</c>. The first
    /// column becomes the primary-key id column; the range partition column has to be declared
    /// explicitly (the library cannot add it to a table that already exists).
    /// </param>
    /// <returns>A fluent <see cref="ITableBuilder"/> for further configuration.</returns>
    ITableBuilder AdoptTable(string tableName, params string[] sqlFields);

    /// <summary>
    /// Validates and materialises all configured tables into <see cref="ITableSettings"/> instances.
    /// </summary>
    /// <returns>An array of immutable table settings ready for runtime use.</returns>
    ITableSettings[] Build();
}
