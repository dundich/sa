    /// <summary>Type table fields (message-type registry, type id ↔ name).</summary>
    public sealed class TypeTable
    {
        /// <summary>The table name suffix ("__type$").</summary>
        public const string Suffix = "__type$";

        /// <summary>Gets or sets the table name. Default is "{Defaults.DatabaseTableName}{Suffix}" (e.g. "outbox__type$").</summary>
        public string TableName { get; set; } = $"{Defaults.DatabaseTableName}{Suffix}";

        /// <summary>Gets the column definitions for the type table.</summary>
        public TableFields Fields { get; } = new();

        /// <summary>Column definitions for the type table.</summary>
        public sealed class TableFields
        {
            /// <summary>Type hash (murmurHash3) — primary key.</summary>
            public string TypeId { get; set; } = OutboxFieldDefaults.TypeId;

            /// <summary>Full type name.</summary>
            public string TypeName { get; set; } = OutboxFieldDefaults.TypeName;

            /// <summary>Returns the exact PostgreSQL column definitions used at table creation.</summary>
            public string[] All() =>
            [
                $"{TypeId} BIGINT NOT NULL",
                $"{TypeName} TEXT NOT NULL"
            ];
        }
    }

    /// <summary>Offset table fields (consumer-group offsets, advisory-locked).</summary>
    public sealed class OffsetTable
    {
        /// <summary>The table name suffix ("__offset$").</summary>
        public const string Suffix = "__offset$";

        /// <summary>Gets or sets the table name. Default is "{Defaults.DatabaseTableName}{Suffix}" (e.g. "outbox__offset$").</summary>
        public string TableName { get; set; } = $"{Defaults.DatabaseTableName}{Suffix}";

        /// <summary>Gets the column definitions for the offset table.</summary>
        public TableFields Fields { get; } = new();

        /// <summary>Column definitions for the offset table.</summary>
        public sealed class TableFields
        {
            /// <summary>Consumer group id — part of the primary key.</summary>
            public string ConsumerGroup { get; set; } = OutboxFieldDefaults.ConsumerGroup;

            /// <summary>Tenant — part of the primary key.</summary>
            public string TenantId { get; set; } = OutboxFieldDefaults.TenantId;

            /// <summary>Last consumed message id (UUID v7) — the offset is a v7 UUID, so it is time-ordered.</summary>
            public string GroupOffset { get; set; } = OutboxFieldDefaults.GroupOffset;

            /// <summary>Last offset update time.</summary>
            public string GroupUpdatedAt { get; set; } = OutboxFieldDefaults.GroupUpdatedAt;

            /// <summary>Returns the exact PostgreSQL column definitions used at table creation.</summary>
            public string[] All() =>
            [
                $"{ConsumerGroup} TEXT",
                $"{TenantId} INT NOT NULL DEFAULT 0",
                $"{GroupOffset} UUID NOT NULL DEFAULT '{Guid.Empty}'",
                $"{GroupUpdatedAt} TIMESTAMP WITH TIME ZONE DEFAULT NOW()"
            ];
        }
    }
}
