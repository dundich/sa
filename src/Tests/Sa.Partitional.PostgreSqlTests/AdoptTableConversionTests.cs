using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging.Abstractions;
using Npgsql;
using Sa.Data.PostgreSql.Fixture;
using Sa.Partitional.PostgreSql;
using Sa.Partitional.PostgreSql.Repositories;
using Sa.Partitional.PostgreSql.SqlBuilder;

namespace Sa.Partitional.PostgreSqlTests;

/// <summary>
/// Integration coverage for adopting an existing plain table: the first migration converts it in
/// place (keeping the original as a backup), creates the partitions its rows need and copies the rows
/// into the partitioned root. The same methods keep working afterwards.
/// </summary>
public class AdoptTableConversionTests(AdoptTableConversionTests.Fixture fixture)
    : IClassFixture<AdoptTableConversionTests.Fixture>
{
    private static readonly DateTimeOffset Today = new(DateTime.UtcNow.Date, TimeSpan.Zero);

    public class Fixture : PgDataSourceFixture<IPartRepository>
    {
        public Fixture()
        {
            Services.AddSaPartitional((_, builder) =>
            {
                builder.AddSchema(schema =>
                {
                    schema.AdoptTable("adopt_empty",
                            "id bigint GENERATED BY DEFAULT AS IDENTITY",
                            "payload text",
                            "created_at bigint NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_data",
                            "id bigint GENERATED BY DEFAULT AS IDENTITY",
                            "payload text",
                            "created_at bigint NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_list",
                            "id bigint GENERATED BY DEFAULT AS IDENTITY",
                            "tenant text NOT NULL",
                            "payload text",
                            "created_at bigint NOT NULL")
                        .PartByList("tenant")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_missing",
                            "id bigint NOT NULL",
                            "created_at bigint NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_foreign",
                            "id bigint NOT NULL",
                            "created_at bigint NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_mismatch",
                            "id bigint NOT NULL",
                            "created_at bigint NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_fk",
                            "id bigint NOT NULL",
                            "created_at bigint NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_drop",
                            "id bigint GENERATED BY DEFAULT AS IDENTITY",
                            "payload text",
                            "created_at bigint NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at")
                        .WithConversionBackup(ConversionBackupMode.Drop);

                    schema.AdoptTable("adopt_tz",
                            "id bigint GENERATED BY DEFAULT AS IDENTITY",
                            "payload text",
                            "created_at timestamptz NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_ts",
                            "id bigint GENERATED BY DEFAULT AS IDENTITY",
                            "payload text",
                            "created_at timestamp NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");

                    schema.AdoptTable("adopt_date",
                            "id bigint GENERATED BY DEFAULT AS IDENTITY",
                            "payload text",
                            "created_at date NOT NULL")
                        .PartByRange(PgPartBy.Day, "created_at");
                });
            })
            .AddDataSource(configure => configure.Options(ob => ob.Configure(o => o.ConnectionString = this.ConnectionString)))
            ;
        }
    }

    private IPartRepository Parts => fixture.Sub;
    private IPartitionManager Manager => fixture.ServiceProvider.GetRequiredService<IPartitionManager>();
    private CancellationToken Ct => TestContext.Current.CancellationToken;

    private Task<long> Count(string qualified) => fixture.DataSource.ExecuteScalarTyped<long>(
        $"SELECT count(*) FROM {qualified};", cancellationToken: Ct);

    private Task<string> RelKind(string table) => fixture.DataSource.ExecuteScalarTyped<string>(
        "SELECT relkind::text FROM pg_class WHERE oid = to_regclass(@table);",
        [new NpgsqlParameter<string>("table", $"public.{table}")], Ct);

    private Task<bool> Exists(string qualified) => fixture.DataSource.ExecuteScalarTyped<bool>(
        "SELECT to_regclass(@name) IS NOT NULL;",
        [new NpgsqlParameter<string>("name", qualified)], Ct);

    private Task CreateEmptyTable(string name) => fixture.DataSource.ExecuteNonQuery($"""
CREATE TABLE public.{name} (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload text,
  created_at bigint NOT NULL
);
""", Ct);

    [Fact]
    public async Task EmptyPlainTable_IsConvertedAndGetsPartitions()
    {
        await CreateEmptyTable("adopt_empty");

        // EnsureParts goes through the same adoption step as Migrate.
        await Manager.EnsureParts("adopt_empty", Today, [], Ct);

        Assert.Equal("p", await RelKind("adopt_empty"));
        Assert.True(await Exists("public.adopt_empty__backup$"));

        long cacheRows = await Count("public.\"adopt_empty__part$\"");
        Assert.Equal(1, cacheRows);

        string partition = $"public.\"adopt_empty__{PgPartBy.Day.Fmt(Today)}\"";
        Assert.True(await Exists(partition));

        // A second run must not convert the table again.
        await Manager.EnsureParts("adopt_empty", Today, [], Ct);

        Assert.Equal("p", await RelKind("adopt_empty"));
        Assert.True(await Exists("public.adopt_empty__backup$"));

        // A fresh adopter simulates a restarted process: its in-memory "already adopted" cache is
        // empty, so this exercises the catalog branch (partitioned root + cache table).
        PartTableAdopter restarted = new(
            fixture.DataSource,
            fixture.ServiceProvider.GetRequiredService<ISqlBuilder>(),
            NullLogger<PartTableAdopter>.Instance);

        await restarted.EnsureAdopted("adopt_empty", Ct);

        Assert.Equal("p", await RelKind("adopt_empty"));
        Assert.True(await Exists("public.adopt_empty__backup$"));
        Assert.Equal(1, await Count("public.\"adopt_empty__part$\""));
    }

    [Fact]
    public async Task PlainTableWithData_KeepsEveryRowAndCreatesTheNeededPartitions()
    {
        await CreateEmptyTable("adopt_data");

        DateTimeOffset older = Today.AddDays(-2);

        await fixture.DataSource.ExecuteNonQuery("""
INSERT INTO public.adopt_data (payload, created_at) VALUES ('today', @today), ('older', @older), ('older-2', @older);
""", [new NpgsqlParameter<long>("today", Today.ToUnixTimeSeconds()), new NpgsqlParameter<long>("older", older.ToUnixTimeSeconds())], Ct);

        await Manager.EnsureParts("adopt_data", Today, [], Ct);

        Assert.Equal("p", await RelKind("adopt_data"));
        Assert.Equal(3, await Count("public.adopt_data"));
        Assert.Equal(3, await Count("public.adopt_data__backup$"));

        Assert.True(await Exists($"public.\"adopt_data__{PgPartBy.Day.Fmt(Today)}\""));
        Assert.True(await Exists($"public.\"adopt_data__{PgPartBy.Day.Fmt(older)}\""));

        // Every period between the oldest and the newest row is created, so the gap day is covered
        // as well (three periods, three cache rows).
        Assert.Equal(3, await Count("public.\"adopt_data__part$\""));

        // A row that has been copied must be readable through the new partitioned root.
        long copied = await fixture.DataSource.ExecuteScalarTyped<long>(
            "SELECT count(*) FROM public.adopt_data WHERE payload LIKE 'older%';", cancellationToken: Ct);
        Assert.Equal(2, copied);

        // The identity sequence was moved past the copied identifiers: a generated id must not
        // collide with the rows the backup already held.
        await fixture.DataSource.ExecuteNonQuery(
            "INSERT INTO public.adopt_data (payload, created_at) VALUES ('after', @date);",
            [new NpgsqlParameter<long>("date", Today.ToUnixTimeSeconds())], Ct);

        Assert.Equal(4, await Count("public.adopt_data"));
        Assert.Equal(1, await fixture.DataSource.ExecuteScalarTyped<long>(
            "SELECT count(*) FROM public.adopt_data WHERE payload = 'after';", cancellationToken: Ct));
    }

    [Fact]
    public async Task ListPartitionedPlainTable_CreatesListLevelsFromData()
    {
        await fixture.DataSource.ExecuteNonQuery("""
CREATE TABLE public.adopt_list (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant text NOT NULL,
  payload text,
  created_at bigint NOT NULL
);
""", Ct);

        await fixture.DataSource.ExecuteNonQuery("""
INSERT INTO public.adopt_list (tenant, payload, created_at) VALUES
  ('tenant_a', 'a-1', @date),
  ('tenant_a', 'a-2', @date),
  ('tenant_b', 'b-1', @date);
""", [new NpgsqlParameter<long>("date", Today.ToUnixTimeSeconds())], Ct);

        await Manager.EnsureParts("adopt_list", Today, ["tenant_a"], Ct);

        Assert.Equal("p", await RelKind("adopt_list"));
        Assert.Equal(3, await Count("public.adopt_list"));
        Assert.True(await Exists("public.\"adopt_list__tenant_a\""));
        Assert.True(await Exists("public.\"adopt_list__tenant_b\""));

        string suffix = PgPartBy.Day.Fmt(Today);
        Assert.True(await Exists($"public.\"adopt_list__tenant_a__{suffix}\""));
        Assert.True(await Exists($"public.\"adopt_list__tenant_b__{suffix}\""));
        Assert.Equal(2, await Count("public.\"adopt_list__part$\""));
    }

    [Fact]
    public async Task ConversionBackupDrop_LeavesNoOriginalTable()
    {
        await CreateEmptyTable("adopt_drop");

        await fixture.DataSource.ExecuteNonQuery(
            "INSERT INTO public.adopt_drop (payload, created_at) VALUES ('kept', @date);",
            [new NpgsqlParameter<long>("date", Today.ToUnixTimeSeconds())], Ct);

        await Manager.EnsureParts("adopt_drop", Today, [], Ct);

        Assert.Equal("p", await RelKind("adopt_drop"));
        Assert.False(await Exists("public.adopt_drop__backup$"));
        Assert.Equal(1, await Count("public.adopt_drop"));
    }

    [Fact]
    public async Task TimestampTzPlainTable_IsConvertedWithoutTouchingTheData()
    {
        await fixture.DataSource.ExecuteNonQuery("""
CREATE TABLE public.adopt_tz (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payload text,
  created_at timestamptz NOT NULL
);
""", Ct);

        await fixture.DataSource.ExecuteNonQuery(
            "INSERT INTO public.adopt_tz (payload, created_at) VALUES ('today', @today), ('older', @older);",
            [
                new NpgsqlParameter<DateTimeOffset>("today", Today.AddHours(12)),
                new NpgsqlParameter<DateTimeOffset>("older", Today.AddDays(-1).AddHours(8)),
            ], Ct);

        await Manager.EnsureParts("adopt_tz", Today, [], Ct);

        Assert.Equal("p", await RelKind("adopt_tz"));
        Assert.True(await Exists("public.adopt_tz__backup$"));
        Assert.Equal(2, await Count("public.adopt_tz"));
        Assert.True(await Exists($"public.\"adopt_tz__{PgPartBy.Day.Fmt(Today)}\""));
        Assert.True(await Exists($"public.\"adopt_tz__{PgPartBy.Day.Fmt(Today.AddDays(-1))}\""));

        // The application keeps writing timestamps — no schema or application change.
        await fixture.DataSource.ExecuteNonQuery(
            "INSERT INTO public.adopt_tz (payload, created_at) VALUES ('after', @date);",
            [new NpgsqlParameter<DateTimeOffset>("date", Today.AddHours(15))], Ct);

        Assert.Equal(3, await Count("public.adopt_tz"));
    }

