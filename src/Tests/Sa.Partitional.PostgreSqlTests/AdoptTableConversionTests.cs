    [Fact]
    public async Task MissingTable_IsRejected()
    {
        InvalidOperationException ex = await Assert.ThrowsAsync<InvalidOperationException>(
            () => Parts.CreatePart("adopt_missing", Today, [], Ct));

        Assert.Contains("does not exist", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ForeignPartitionedTable_IsRejected()
    {
        await fixture.DataSource.ExecuteNonQuery("""
CREATE TABLE public.adopt_foreign (
  id bigint NOT NULL,
  created_at bigint NOT NULL
) PARTITION BY RANGE (created_at);
""", Ct);

        InvalidOperationException ex = await Assert.ThrowsAsync<InvalidOperationException>(
            () => Parts.CreatePart("adopt_foreign", Today, [], Ct));

        Assert.Contains("already partitioned", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ColumnMismatch_RollsTheConversionBack()
    {
        await fixture.DataSource.ExecuteNonQuery("""
CREATE TABLE public.adopt_mismatch (
  id bigint NOT NULL,
  extra text,
  created_at bigint NOT NULL
);
""", Ct);

        InvalidOperationException ex = await Assert.ThrowsAsync<InvalidOperationException>(
            () => Parts.CreatePart("adopt_mismatch", Today, [], Ct));

        Assert.Contains("does not match", ex.Message, StringComparison.Ordinal);

        // The transaction rolled back: the original table is still plain and the backup was never
        // created.
        Assert.Equal("r", await RelKind("adopt_mismatch"));
        Assert.False(await Exists("public.adopt_mismatch__backup$"));
    }

    [Fact]
    public async Task IncomingForeignKey_BlocksTheConversion()
    {
        await fixture.DataSource.ExecuteNonQuery("""
CREATE TABLE public.adopt_fk (
  id bigint PRIMARY KEY,
  created_at bigint NOT NULL
);

CREATE TABLE public.adopt_fk_child (
  id bigint PRIMARY KEY,
  parent_id bigint REFERENCES public.adopt_fk (id)
);
""", Ct);

        InvalidOperationException ex = await Assert.ThrowsAsync<InvalidOperationException>(
            () => Parts.CreatePart("adopt_fk", Today, [], Ct));

        Assert.Contains("foreign keys", ex.Message, StringComparison.Ordinal);
        Assert.Equal("r", await RelKind("adopt_fk"));
        Assert.False(await Exists("public.adopt_fk__backup$"));
    }
}
