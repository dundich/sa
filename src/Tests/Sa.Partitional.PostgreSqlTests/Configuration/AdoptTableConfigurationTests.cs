using Sa.Partitional.PostgreSql;
using Sa.Partitional.PostgreSql.Configuration.Builder;
using Sa.Partitional.PostgreSql.SqlBuilder;

namespace Sa.Partitional.PostgreSqlTests.Configuration;

/// <summary>
/// Configuration-level behaviour of <see cref="ISchemaBuilder.AdoptTable"/>: the table is registered
/// in Adopt mode, repeated identical declarations merge, conflicting ones fail while they are still
/// identifiable, and the generated SQL never creates the root table.
/// </summary>
public class AdoptTableConfigurationTests
{
    private const string Id = "id bigint GENERATED BY DEFAULT AS IDENTITY";

    [Fact]
    public void AdoptTable_SetsAdoptModeAndFields()
    {
        SchemaBuilder builder = new("public");
        builder.AdoptTable("t", Id, "payload text", "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at");

        ITableSettings settings = builder.Build().Single();

        Assert.Equal(TableRootMode.Adopt, settings.RootMode);
        Assert.Equal("id", settings.IdFieldName);
        Assert.Equal("created_at", settings.PartByRangeFieldName);
    }

    [Fact]
    public void AdoptTable_TwiceWithTheSameFields_IsIdempotent()
    {
        SchemaBuilder builder = new("public");

        builder.AdoptTable("t", Id, "payload text", "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at");

        // The module builder merges repeated declarations; repeating an identical adopt call must
        // not append the fields a second time.
        builder.AdoptTable("t", Id, "payload text", "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at");

        ITableSettings settings = builder.Build().Single();

        Assert.Equal(3, settings.Fields.Length);
        Assert.Equal(TableRootMode.Adopt, settings.RootMode);
    }

    [Fact]
    public void AdoptTable_TwiceWithDifferentFields_Throws()
    {
        SchemaBuilder builder = new("public");
        builder.AdoptTable("t", Id, "created_at bigint NOT NULL");

        InvalidOperationException ex = Assert.Throws<InvalidOperationException>(
            () => builder.AdoptTable("t", Id, "payload text", "created_at bigint NOT NULL"));

        Assert.Contains("different fields", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void AddTable_ThenAdoptTable_Throws()
    {
        SchemaBuilder builder = new("public");
        builder.AddTable("t", Id, "created_at bigint NOT NULL");

        InvalidOperationException ex = Assert.Throws<InvalidOperationException>(
            () => builder.AdoptTable("t", Id, "created_at bigint NOT NULL"));

        Assert.Contains("already declared", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void AdoptTable_WithoutFields_Throws()
    {
        SchemaBuilder builder = new("public");

        Assert.Throws<ArgumentException>(() => builder.AdoptTable("t"));
    }

    [Fact]
    public void AdoptTable_WithoutDeclaredRangeColumn_Throws()
    {
        SchemaBuilder builder = new("public");
        builder.AdoptTable("t", Id, "payload text")
            .PartByRange(PgPartBy.Day, "created_at");

        InvalidOperationException ex = Assert.Throws<InvalidOperationException>(() => builder.Build());

        Assert.Contains("cannot be extended", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void AdoptTable_ConversionBackupDefaultsToKeep()
    {
        SchemaBuilder builder = new("public");
        builder.AdoptTable("t", Id, "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at");

        Assert.Equal(ConversionBackupMode.Keep, builder.Build().Single().ConversionBackup);
    }

    [Fact]
    public void AdoptTable_WithConversionBackupDrop_IsRecorded()
    {
        SchemaBuilder builder = new("public");
        builder.AdoptTable("t", Id, "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at")
            .WithConversionBackup(ConversionBackupMode.Drop);

        Assert.Equal(ConversionBackupMode.Drop, builder.Build().Single().ConversionBackup);
    }

    [Fact]
    public void AdoptTable_WithInlinePrimaryKey_Throws()
    {
        SchemaBuilder builder = new("public");
        builder.AdoptTable("t", "id bigint PRIMARY KEY", "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at");

        InvalidOperationException ex = Assert.Throws<InvalidOperationException>(() => builder.Build());

        Assert.Contains("inline PRIMARY KEY", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void AdoptTable_CreateSqlDoesNotEmitTheRootTable()
    {
        SchemaBuilder builder = new("public");
        builder.AdoptTable("t", Id, "payload text", "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at");

        ITableSettings settings = builder.Build().Single();
        string sql = new SqlTableBuilder(settings).CreateSql(DateTimeOffset.UnixEpoch);

        Assert.DoesNotContain("CREATE TABLE IF NOT EXISTS \"public\".\"t\" (", sql, StringComparison.Ordinal);
        Assert.Contains("PARTITION OF \"public\".\"t\"", sql, StringComparison.Ordinal);
        Assert.Contains("\"public\".\"t__part$\"", sql, StringComparison.Ordinal);
    }

    [Fact]
    public void CreateMode_StillEmitsTheRootTable()
    {
        SchemaBuilder builder = new("public");
        builder.AddTable("t", Id, "payload text", "created_at bigint NOT NULL")
            .PartByRange(PgPartBy.Day, "created_at");

        ITableSettings settings = builder.Build().Single();
        string sql = new SqlTableBuilder(settings).CreateSql(DateTimeOffset.UnixEpoch);

        Assert.Contains("CREATE TABLE IF NOT EXISTS \"public\".\"t\" (", sql, StringComparison.Ordinal);
    }
}
